import { start } from './lib.mjs';
const PASS = 'violet otter juggles ninety lanterns';
const KEY = 'sk-ant-api03-FAKEFAKEFAKE-wxyz';
const { page, shot, done } = await start('knockknock-2');
page.setDefaultTimeout(8000);
const step = async (name, fn) => { try { await fn(); } catch (e) { const m = e.message.split('\n')[0]; console.log(`!!! ${name}: ${m}`); await shot(`${name}-FAILED`, m); } };
const keyCard = () => page.locator('section[aria-labelledby="key-title"]');
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ');
await page.goto('http://127.0.0.1:5181/'); await page.waitForLoadState('networkidle');
await step('bad-username', async () => {
  await page.getByLabel('Username').fill('Bob!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.waitForTimeout(500);
  await shot('bad-username', await txt(page.locator('header')));
});
await step('sign-in', async () => {
  await page.getByLabel('Username').fill('bob');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByLabel('New passphrase').fill('short');
  await page.getByLabel('Confirm passphrase').fill('shorter');
  await page.waitForTimeout(300);
  await shot('weak-mismatch', await txt(page.locator('section[aria-labelledby="create-title"]')));
  await page.getByLabel('New passphrase').fill(PASS);
  await page.getByLabel('Confirm passphrase').fill(PASS);
  await page.getByRole('button', { name: 'Create vault' }).click();
  await page.getByText('Your vault is unlocked.').waitFor({ timeout: 30000 });
  await page.getByRole('textbox', { name: 'Anthropic API key' }).fill(KEY);
  await page.getByRole('button', { name: 'Save key' }).click();
  await keyCard().getByText('Saved key:').waitFor();
  await page.getByRole('button', { name: 'Lock' }).click();
  await page.getByRole('heading', { name: 'Your vault is locked' }).waitFor();
  await shot('locked');
});
await step('show-locked-then-dialog-unlock', async () => {
  await keyCard().getByRole('button', { name: 'Show' }).click();
  const dlg = page.locator('dialog[open]');
  await dlg.waitFor();
  await dlg.getByLabel('Passphrase', { exact: true }).fill('wrong passphrase here');
  await dlg.getByRole('button', { name: 'Unlock' }).click();
  await page.waitForTimeout(3000);
  await shot('dialog-wrong', await txt(dlg));
  await dlg.getByLabel('Passphrase', { exact: true }).fill(PASS);
  await dlg.getByRole('button', { name: 'Unlock' }).click();
  await page.getByText('Your vault is unlocked.').waitFor({ timeout: 30000 });
  await page.waitForTimeout(300);
  await shot('dialog-unlocked', `dialog open: ${await page.locator('dialog[open]').count()}; key row: ${await txt(keyCard().locator('p.row'))}`);
});
await step('cancel-dialog', async () => {
  await page.getByRole('button', { name: 'Lock' }).click();
  await page.getByRole('heading', { name: 'Your vault is locked' }).waitFor();
  await page.getByLabel("Who's there?").fill('Cancel');
  await page.getByRole('button', { name: 'Knock' }).click();
  const dlg = page.locator('dialog[open]');
  await dlg.waitFor();
  await dlg.getByRole('button', { name: 'Cancel' }).click();
  await page.waitForTimeout(500);
  await shot('dialog-cancelled', `dialog open: ${await page.locator('dialog[open]').count()}; knock card: ${await txt(page.locator('section[aria-labelledby="knock-title"]'))}`);
});
await step('sign-out', async () => {
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.waitForLoadState('networkidle');
  await page.getByLabel('Username').waitFor();
  await shot('signed-out', await txt(page.locator('main')));
  await page.getByLabel('Username').fill('bob');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('heading', { name: 'Your vault is locked' }).waitFor({ timeout: 15000 });
  await page.waitForTimeout(300);
  await shot('signed-in-again', await txt(page.locator('main')));
});
await done();
